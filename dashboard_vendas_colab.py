# Parte 2, gráfico 1: filtro de Mês -> faturamento por produto
@app.callback(Output("graf-produtos-mes", "figure"),
              Input("filtro-mes", "value"))
def atualizar_produtos_mes(meses):
    dados = df[df["Mes_Num"].isin(meses)] if meses else df
    agrupado = total_por(dados, "Nome_Produto").head(10).sort_values("Valor_Total_Venda")
    fig = px.bar(agrupado, x="Valor_Total_Venda", y="Nome_Produto", orientation="h",
                 color_discrete_sequence=[COR_PRINCIPAL])
    fig.update_traces(hovertemplate="%{y}<br>R$ %{x:,.2f}<extra></extra>")
    estilizar(fig, titulo_y="")
    fig.update_xaxes(tickprefix="R$ ", showgrid=True, gridcolor="#E6E9EE")
    fig.update_yaxes(tickprefix="", gridcolor="white")
    return fig


# Parte 2, gráfico 2: filtro de Representante -> faturamento mês a mês,
# comparado com a média da equipe
@app.callback(Output("graf-representante-mes", "figure"),
              Input("filtro-representante", "value"))
def atualizar_representante(representante):
    do_rep = total_por_mes(df[df["Nome_Representante"] == representante])
    do_rep["Série"] = representante

    media = total_por_mes(df)
    media["Valor_Total_Venda"] = media["Valor_Total_Venda"] / df["Nome_Representante"].nunique()
    media["Série"] = "Média da equipe"

    fig = px.line(pd.concat([do_rep, media]), x="Mes", y="Valor_Total_Venda",
                  color="Série", markers=True, line_dash="Série",
                  color_discrete_sequence=[COR_PRINCIPAL, "#9AA5B1"],
                  line_dash_sequence=["solid", "dot"])
    fig.update_traces(hovertemplate=HOVER_REAIS)
    estilizar(fig)
    fig.update_layout(legend=dict(orientation="h", y=1.1, x=0))
    return fig


# Parte 2, gráfico 3: filtros de Cliente e Regional -> faturamento por produto
@app.callback(Output("graf-cliente-produto", "figure"),
              Input("filtro-cliente", "value"),
              Input("filtro-regional", "value"))
def atualizar_cliente(cliente, regional):
    dados = df[df["Nome_Cliente"] == cliente]
    if regional != "Todas":
        dados = dados[dados["Regional"] == regional]
    if dados.empty:
        return figura_vazia(f"Nenhuma venda para {cliente} nesta regional.")

    agrupado = total_por(dados, "Nome_Produto").sort_values("Valor_Total_Venda")
    fig = px.bar(agrupado, x="Valor_Total_Venda", y="Nome_Produto", orientation="h",
                 color_discrete_sequence=[COR_DESTAQUE])
    fig.update_traces(hovertemplate="%{y}<br>R$ %{x:,.2f}<extra></extra>")
    estilizar(fig, titulo_y="")
    fig.update_xaxes(tickprefix="R$ ", showgrid=True, gridcolor="#E6E9EE")
    fig.update_yaxes(tickprefix="", gridcolor="white")
    return fig


# Parte 3, filtro encadeado (passo 1): o Estado define as opções de Cidade.
# O valor volta para None para não manter selecionada uma cidade de outro estado.
@app.callback(Output("filtro-cidade", "options"),
              Output("filtro-cidade", "value"),
              Input("filtro-estado", "value"))
def atualizar_cidades(estado):
    cidades = sorted(df.loc[df["Estado_Cliente"] == estado, "Cidade_Cliente"].unique())
    return [{"label": c, "value": c} for c in cidades], None


# Parte 3, filtro encadeado (passo 2): Estado + Cidade -> faturamento por cliente
@app.callback(Output("graf-cidade", "figure"),
              Input("filtro-estado", "value"),
              Input("filtro-cidade", "value"))
def atualizar_grafico_cidade(estado, cidade):
    dados = df[df["Estado_Cliente"] == estado]
    if cidade:
        dados = dados[dados["Cidade_Cliente"] == cidade]

    agrupado = (dados.groupby(["Nome_Cliente", "Cidade_Cliente"], as_index=False)
                ["Valor_Total_Venda"].sum()
                .sort_values("Valor_Total_Venda", ascending=False))
    # Ordena os clientes pelo total somado de todas as cidades
    ordem = total_por(dados, "Nome_Cliente")["Nome_Cliente"].tolist()
    fig = px.bar(agrupado, x="Nome_Cliente", y="Valor_Total_Venda",
                 color="Cidade_Cliente", barmode="group",
                 category_orders={"Nome_Cliente": ordem},
                 color_discrete_sequence=[COR_PRINCIPAL, COR_DESTAQUE])
    fig.update_traces(hovertemplate="%{x}<br>R$ %{y:,.2f}<extra></extra>")
    estilizar(fig)
    fig.update_layout(legend=dict(orientation="h", y=1.1, x=0))
    return fig

