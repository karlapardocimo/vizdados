# 1. CARGA E TRATAMENTO DA BASE
CAMINHO_BASE = NOME_ARQUIVO  # arquivo enviado na célula anterior

MESES = {1: "Jan", 2: "Fev", 3: "Mar", 4: "Abr", 5: "Mai", 6: "Jun",
         7: "Jul", 8: "Ago", 9: "Set", 10: "Out", 11: "Nov", 12: "Dez"}


def carregar_dados() -> pd.DataFrame:
    df = pd.read_excel(CAMINHO_BASE)

    # A planilha tem uma primeira coluna vazia ("Unnamed: 0"): removemos
    # todas as colunas sem nenhum valor.
    df = df.dropna(axis=1, how="all")

    # Espaços sobrando no texto (ex.: "Teclado " com espaço no final)
    colunas_texto = df.select_dtypes(include=["object", "string"]).columns
    for col in colunas_texto:
        df[col] = df[col].str.strip()

    # Padronização: Minas aparece como "MINAS" e os outros estados pela sigla
    df["Estado_Cliente"] = df["Estado_Cliente"].replace({"MINAS": "MG"})

    # Padronização dos nomes de clientes escritos em minúsculas
    df["Nome_Cliente"] = df["Nome_Cliente"].replace({"amazon": "Amazon",
                                                     "kabum": "KaBuM"})

    # Garante que só entram vendas de 2020 (a base já está toda em 2020,
    # mas o filtro deixa a regra explícita)
    df["Data_Pedido"] = pd.to_datetime(df["Data_Pedido"])
    df = df[df["Data_Pedido"].dt.year == 2020].copy()

    # Colunas de mês: o número serve para ordenar e o nome para exibir
    df["Mes_Num"] = df["Data_Pedido"].dt.month
    df["Mes"] = df["Mes_Num"].map(MESES)
    return df


